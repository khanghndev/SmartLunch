CREATE TABLE organizations (
    Id INT NOT NULL AUTO_INCREMENT,
    Code VARCHAR(20) NULL COMMENT 'Mã tự sinh (trigger)',
    Name VARCHAR(255) NOT NULL COMMENT 'Tên đơn vị',
    TaxCode VARCHAR(50) NULL COMMENT 'Mã số thuế',
    LegalRepresentative VARCHAR(255) NULL COMMENT 'Người đại diện pháp luật',
    Address VARCHAR(255) NULL,
    Phone VARCHAR(50) NULL,
    ContactPerson VARCHAR(255) NULL,
    ContactEmail VARCHAR(255) NULL,
    LogoUrl VARCHAR(500) NULL COMMENT 'Logo đơn vị',
    Website VARCHAR(255) NULL,
    Type VARCHAR(50) NOT NULL DEFAULT 'Office' COMMENT 'Office | Factory | School',
    EducationLevel VARCHAR(50) NULL COMMENT 'Mẫu giáo | Tiểu học | THCS | THPT (nếu là School)',
    IsSubscriptionActive TINYINT(1) NOT NULL DEFAULT 0,
    DefaultDailyMeals INT NOT NULL DEFAULT 0,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    CreatedBy INT NULL,
    UpdatedBy INT NULL,
    PRIMARY KEY (Id),
    UNIQUE KEY UK_organizations_code (Code),
    UNIQUE KEY UK_organizations_name (Name),
    INDEX IX_organizations_active (IsActive),
    CONSTRAINT FK_organizations_created_by FOREIGN KEY (CreatedBy) REFERENCES users (Id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT FK_organizations_updated_by FOREIGN KEY (UpdatedBy) REFERENCES users (Id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC COMMENT = 'Đơn vị đặt hàng';
