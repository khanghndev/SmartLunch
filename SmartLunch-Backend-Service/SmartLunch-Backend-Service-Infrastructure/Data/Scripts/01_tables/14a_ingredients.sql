CREATE TABLE ingredients (
    Id INT NOT NULL AUTO_INCREMENT,
    Code VARCHAR(20) NULL COMMENT 'Mã tự sinh (trigger)',
    Name VARCHAR(255) NOT NULL COMMENT 'Tên nguyên liệu (tiếng Việt)',
    NameEnglish VARCHAR(100) NULL COMMENT 'Tên nguyên liệu tiếng Anh (dùng cho AI grouping: pork|chicken|shrimp|...)',
    Unit VARCHAR(20) NOT NULL COMMENT 'Đơn vị (kg, lít, ...)',
    Description VARCHAR(255) NULL COMMENT 'Mô tả',
    DefaultSupplierId INT NULL,
    CostPerUnit DECIMAL(10,2) NULL,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    CategoryId INT,
    PRIMARY KEY (Id),
    UNIQUE KEY UK_ingredients_code (Code),
    UNIQUE KEY UK_ingredients_name (Name),
    INDEX IX_ingredients_category (CategoryId),
    INDEX IX_ingredients_supplier (DefaultSupplierId),
    CONSTRAINT FK_ingredients_supplier FOREIGN KEY (DefaultSupplierId) REFERENCES partners (Id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT FK_ingredients_category FOREIGN KEY (CategoryId) REFERENCES ingredient_categories(Id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci ROW_FORMAT = DYNAMIC COMMENT = 'Nguyên liệu';
